def load_ci_summary():
    """
    Load bootstrap CI summary.

    Supports either:
        results/tables/bootstrap_ci_summary.csv
    or:
        bootstrap_ci_summary.csv
    """

    candidates = [
        BOOTSTRAP_CI_CSV,
        Path("bootstrap_ci_summary.csv"),
    ]

    for path in candidates:
        if path.exists():
            print(f"Loading bootstrap CIs from: {path}")
            return pd.read_csv(path)

    print("WARNING: bootstrap CI summary not found.")
    return None


def normalize_ci_columns(ci_df):
    """
    Normalize common CI column naming conventions.

    The plotting code expects:

        tag
        strict_acc_ci_lo
        strict_acc_ci_hi
        coverage_ci_lo
        coverage_ci_hi
        abstain_rate_ci_lo
        abstain_rate_ci_hi

    If the file already uses these names, nothing changes.
    """

    if ci_df is None:
        return None

    df = ci_df.copy()

    aliases = {
        "system": "tag",

        "strict_accuracy_ci_lo": "strict_acc_ci_lo",
        "strict_accuracy_ci_low": "strict_acc_ci_lo",
        "strict_acc_low": "strict_acc_ci_lo",
        "strict_acc_lower": "strict_acc_ci_lo",

        "strict_accuracy_ci_hi": "strict_acc_ci_hi",
        "strict_accuracy_ci_high": "strict_acc_ci_hi",
        "strict_acc_high": "strict_acc_ci_hi",
        "strict_acc_upper": "strict_acc_ci_hi",

        "coverage_ci_low": "coverage_ci_lo",
        "coverage_lower": "coverage_ci_lo",

        "coverage_ci_high": "coverage_ci_hi",
        "coverage_upper": "coverage_ci_hi",

        "abstention_rate_ci_low": "abstain_rate_ci_lo",
        "abstain_ci_lo": "abstain_rate_ci_lo",
        "abstention_lower": "abstain_rate_ci_lo",

        "abstention_rate_ci_high": "abstain_rate_ci_hi",
        "abstain_ci_hi": "abstain_rate_ci_hi",
        "abstention_upper": "abstain_rate_ci_hi",
    }

    for old, new in aliases.items():
        if old in df.columns and new not in df.columns:
            df[new] = df[old]

    return df


def load_metrics():
    df = pd.read_csv(METRICS_CSV)

    required = {
        "system",
        "strict_accuracy",
        "coverage",
        "abstention_rate",
        "n",
    }

    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            f"metrics.csv is missing required columns: {sorted(missing)}"
        )

    df["system"] = pd.Categorical(
        df["system"],
        categories=SYSTEM_ORDER,
        ordered=True,
    )

    df = (
        df
        .sort_values("system")
        .reset_index(drop=True)
    )

    ci_df = normalize_ci_columns(load_ci_summary())

    if ci_df is not None and "tag" in ci_df.columns:
        df = df.merge(
            ci_df,
            left_on="system",
            right_on="tag",
            how="left",
            suffixes=("", "_ci_df"),
        )

    return df


def load_ablation():
    df = pd.read_csv(ABLATION_CSV)

    required = {
        "system",
        "model",
        "strict_acc",
        "coverage",
        "sel_acc",
        "errors",
        "total",
    }

    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            f"model_ablation_summary.csv is missing required columns: "
            f"{sorted(missing)}"
        )

    df["failed"] = df["errors"] == df["total"]

    ci_df = normalize_ci_columns(load_ci_summary())

    if ci_df is not None and "tag" in ci_df.columns:
        df = df.merge(
            ci_df,
            left_on="model",
            right_on="tag",
            how="left",
            suffixes=("", "_ci_df"),
        )

    return df


