# Optional true confusion matrix
# ============================================================================

def plot_confusion_matrix(
    jsonl_path,
    pred_col="verdict",
    gold_col="gold_label",
):

    records = []

    with open(
        jsonl_path,
        encoding="utf-8",
    ) as f:

        for line in f:
            line = line.strip()

            if line:
                records.append(
                    json.loads(line)
                )

    preds = sorted(
        {
            r[pred_col]
            for r in records
        }
    )

    golds = sorted(
        {
            r[gold_col]
            for r in records
        }
    )

    mat = np.zeros(
        (
            len(golds),
            len(preds),
        ),
        dtype=int,
    )

    for r in records:

        i = golds.index(
            r[gold_col]
        )

        j = preds.index(
            r[pred_col]
        )

        mat[i, j] += 1

    fig, ax = plt.subplots(
        figsize=(6.5, 5.5)
    )

    im = ax.imshow(
        mat,
        cmap="Blues",
    )

    ax.set_xticks(
        range(len(preds))
    )

    ax.set_xticklabels(
        preds,
        rotation=30,
        ha="right",
    )

    ax.set_yticks(
        range(len(golds))
    )

    ax.set_yticklabels(
        golds
    )

    ax.set_xlabel(
        "Predicted verdict"
    )

    ax.set_ylabel(
        "Gold label"
    )

    for i in range(
        len(golds)
    ):

        for j in range(
            len(preds)
        ):

            ax.text(
                j,
                i,
                mat[i, j],
                ha="center",
                va="center",
            )

    fig.colorbar(
        im,
        ax=ax,
        label="Count",
    )

    ax.set_title(
        f"Confusion matrix: "
        f"{Path(jsonl_path).stem}"
    )

    savefig(
        fig,
        f"confusion_matrix_"
        f"{Path(jsonl_path).stem}",
    )


