def plot_cross_lingual_slope(df):

    d = df.set_index("system")

    fig, ax = plt.subplots(
        figsize=(8.5, 5.8)
    )

    parametric_x = [
        0,
        1,
    ]

    parametric_y = [
        d.loc["S1", "strict_accuracy"],
        d.loc["S2", "strict_accuracy"],
    ]

    rag_x = [
        0,
        1,
        2,
    ]

    rag_y = [
        d.loc["S3_BM25", "strict_accuracy"],
        d.loc["S4_BM25", "strict_accuracy"],
        d.loc["S4_TRANS", "strict_accuracy"],
    ]

    if available_ci(
        df,
        "strict_acc_ci_lo",
        "strict_acc_ci_hi",
    ):

        parametric_lo = [
            d.loc["S1", "strict_acc_ci_lo"],
            d.loc["S2", "strict_acc_ci_lo"],
        ]

        parametric_hi = [
            d.loc["S1", "strict_acc_ci_hi"],
            d.loc["S2", "strict_acc_ci_hi"],
        ]

        rag_lo = [
            d.loc["S3_BM25", "strict_acc_ci_lo"],
            d.loc["S4_BM25", "strict_acc_ci_lo"],
            d.loc["S4_TRANS", "strict_acc_ci_lo"],
        ]

        rag_hi = [
            d.loc["S3_BM25", "strict_acc_ci_hi"],
            d.loc["S4_BM25", "strict_acc_ci_hi"],
            d.loc["S4_TRANS", "strict_acc_ci_hi"],
        ]

        ax.errorbar(
            parametric_x,
            parametric_y,
            yerr=get_yerr(
                pd.Series(parametric_y),
                pd.Series(parametric_lo),
                pd.Series(parametric_hi),
            ),
            fmt="-o",
            capsize=4,
            linewidth=2,
            label="Parametric",
        )

        ax.errorbar(
            rag_x,
            rag_y,
            yerr=get_yerr(
                pd.Series(rag_y),
                pd.Series(rag_lo),
                pd.Series(rag_hi),
            ),
            fmt="-o",
            capsize=4,
            linewidth=2,
            label="RAG",
        )

    else:

        ax.plot(
            parametric_x,
            parametric_y,
            "-o",
            linewidth=2,
            label="Parametric",
        )

        ax.plot(
            rag_x,
            rag_y,
            "-o",
            linewidth=2,
            label="RAG",
        )

    ax.set_xticks(
        [0, 1, 2]
    )

    ax.set_xticklabels(
        [
            "English",
            "Bangla",
            "Bangla\ntranslated",
        ]
    )

    ax.set_ylabel(
        "Strict accuracy"
    )

    ax.set_ylim(
        0,
        0.55,
    )

    ax.set_title(
        "Cross-lingual degradation and translation recovery"
    )

    ax.legend()

    ax.grid(
        alpha=0.25
    )

    savefig(
        fig,
        "03_cross_lingual_slope",
    )


