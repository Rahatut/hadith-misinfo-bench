def plot_system_headline(df):

    fig, ax = plt.subplots(
        figsize=(11, 6)
    )

    x = np.arange(len(df))
    w = 0.24

    strict_ci = None
    coverage_ci = None
    abstention_ci = None

    if available_ci(
        df,
        "strict_acc_ci_lo",
        "strict_acc_ci_hi",
    ):
        strict_ci = get_yerr(
            df["strict_accuracy"],
            df["strict_acc_ci_lo"],
            df["strict_acc_ci_hi"],
        )

    if available_ci(
        df,
        "coverage_ci_lo",
        "coverage_ci_hi",
    ):
        coverage_ci = get_yerr(
            df["coverage"],
            df["coverage_ci_lo"],
            df["coverage_ci_hi"],
        )

    if available_ci(
        df,
        "abstain_rate_ci_lo",
        "abstain_rate_ci_hi",
    ):
        abstention_ci = get_yerr(
            df["abstention_rate"],
            df["abstain_rate_ci_lo"],
            df["abstain_rate_ci_hi"],
        )

    ax.bar(
        x - w,
        df["strict_accuracy"],
        w,
        label="Strict accuracy",
        yerr=strict_ci,
        capsize=3,
    )

    ax.bar(
        x,
        df["coverage"],
        w,
        label="Coverage",
        yerr=coverage_ci,
        capsize=3,
    )

    ax.bar(
        x + w,
        df["abstention_rate"],
        w,
        label="Abstention rate",
        yerr=abstention_ci,
        capsize=3,
    )

    ax.set_xticks(x)

    ax.set_xticklabels(
        [
            SYSTEM_LABELS[s]
            for s in df["system"]
        ]
    )

    ax.set_ylabel("Rate")

    ax.set_ylim(
        0,
        1.08,
    )

    ax.set_title(
        "System comparison: accuracy, coverage, and abstention"
    )

    ax.legend()

    ax.grid(
        axis="y",
        alpha=0.25,
    )

    savefig(
        fig,
        "01_system_headline",
    )


