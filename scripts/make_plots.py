def build_outcome_breakdown(df):
    """
    Derive:

        correct
        incorrect committed
        abstained

    from system-level metrics.

    This is NOT a label-level confusion matrix.
    """

    out = df.copy()

    out["n_covered"] = (
        out["coverage"] * out["n"]
    )

    out["n_correct"] = (
        out["strict_accuracy"] * out["n"]
    )

    out["n_incorrect_committed"] = (
        out["n_covered"] -
        out["n_correct"]
    )

    out["n_abstained"] = (
        out["n"] -
        out["n_covered"]
    )

    return out


