def available_ci(df, low_col, high_col):
    return (
        low_col in df.columns
        and high_col in df.columns
        and df[low_col].notna().any()
        and df[high_col].notna().any()
    )


def get_yerr(point_series, lo_series, hi_series):
    """
    Return asymmetric error bars for matplotlib.
    """

    point = np.asarray(point_series, dtype=float)
    lo = np.asarray(lo_series, dtype=float)
    hi = np.asarray(hi_series, dtype=float)

    err_lo = np.maximum(0, point - lo)
    err_hi = np.maximum(0, hi - point)

    return np.array([err_lo, err_hi])


def add_value_labels(
    ax,
    xs,
    ys,
    fmt="{:.1%}",
    offset=0.02,
):
    for x, y in zip(xs, ys):
        ax.text(
            x,
            y + offset,
            fmt.format(y),
            ha="center",
            va="bottom",
            fontsize=8,
        )


def savefig(fig, name):
    OUT_DIR.mkdir(exist_ok=True)

    path = OUT_DIR / f"{name}.png"

    fig.savefig(
        path,
        dpi=180,
        bbox_inches="tight",
    )

    plt.close(fig)

    print(f"wrote {path}")


